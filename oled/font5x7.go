// Glyph dimensions. CharW is the advance including the inter-character gap.
const (
	GlyphW = 5
	GlyphH = 7
	CharW  = GlyphW + 1
	LineH  = GlyphH + 1
)

// glyph returns the column bitmap for r, substituting '?' for anything outside
// printable ASCII. Returning a visible substitute rather than skipping keeps
// column arithmetic correct: a caller that measured a string before drawing it
// would otherwise disagree with what landed on the screen.
func glyph(r rune) [5]byte {
	if r < 0x20 || r > 0x7E {
		r = '?'
	}
	return font5x7[r-0x20]
}

// TextWidth is the pixel width of s as drawn, including the gap after every
// character except the last.
func TextWidth(s string) int {
	n := len([]rune(s))
	if n == 0 {
		return 0
	}
	return n*CharW - 1
}
